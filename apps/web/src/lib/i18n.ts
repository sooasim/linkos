/** Cookie value → app locale. The guest picker may store "ja"; the app has no Japanese shell yet → English. */
export function toAppLocale(v: string | null | undefined): AppLocale {
  const o = (v ?? "").trim().toLowerCase().slice(0, 2);
  if (o === "en" || o === "ja") return "en";
  return "ko";
}

