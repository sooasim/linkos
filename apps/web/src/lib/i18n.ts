/** Split a template around a single "{em}" (or other) slot so callers can render a React node there. */
export function slot(template: string, key = "em"): [string, string] {
  const i = template.indexOf(`{${key}}`);
  if (i < 0) return [template, ""];
  return [template.slice(0, i), template.slice(i + key.length + 2)];
}
