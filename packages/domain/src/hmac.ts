// Pure-TypeScript SHA-256 / HMAC-SHA256 (FIPS 180-4, RFC 2104).
// Used where WebCrypto is unavailable (React Native Hermes) so that the native app and the server
// compute byte-identical signatures for F-052 offline receipts. No I/O.

